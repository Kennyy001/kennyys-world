create table if not exists public.tracks (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 100),
  artist text not null default 'Kennyy' check (char_length(artist) between 1 and 100),
  language text not null default 'Other' check (char_length(language) between 1 and 30),
  audio_path text not null,
  cover_url text,
  owner_id uuid not null,
  like_count integer not null default 0 check (like_count >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.likes (
  id bigint generated by default as identity primary key,
  track_id bigint not null references public.tracks(id) on delete cascade,
  device_id text not null check (char_length(device_id) between 1 and 100),
  created_at timestamptz not null default now(),
  unique(track_id, device_id)
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  nickname text not null check (char_length(trim(nickname)) between 1 and 32),
  body text not null check (char_length(trim(body)) between 1 and 500),
  created_at timestamptz not null default now()
);

create or replace function public.refresh_track_like_count()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    update public.tracks set like_count = like_count + 1 where id = new.track_id;
    return new;
  elsif tg_op = 'DELETE' then
    update public.tracks set like_count = greatest(0, like_count - 1) where id = old.track_id;
    return old;
  end if;
  return null;
end;
$$;

drop trigger if exists likes_update_count_insert on public.likes;
create trigger likes_update_count_insert after insert on public.likes
for each row execute function public.refresh_track_like_count();
drop trigger if exists likes_update_count_delete on public.likes;
create trigger likes_update_count_delete after delete on public.likes
for each row execute function public.refresh_track_like_count();

